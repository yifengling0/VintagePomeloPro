#!/usr/bin/env python3
"""Single source for GStreamer staging, Wine's explicit loader and HAP checks."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import struct

INVENTORY = json.loads(Path(__file__).with_name("gstreamer_plugins.json").read_text())
PLUGINS = tuple(INVENTORY["plugins"])
REQUIRED_PLUGINS = tuple(INVENTORY["requiredPlugins"])
REQUIRED_ELEMENTS = tuple(INVENTORY["requiredElements"])
VERSION = INVENTORY["version"]


def fingerprint(files):
    content = {"inventory": INVENTORY, "files": files}
    return hashlib.sha256(json.dumps(content, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def check_elf(data, arch, label):
    machine = {"aarch64": 183, "x86_64": 62}[arch]
    if len(data) < 64 or data[:6] != b"\x7fELF\x02\x01" or struct.unpack_from("<HH", data, 16) != (3, machine):
        raise ValueError(f"{label}: expected {arch} ELF64 shared library")


def describe(directory, wine_arch, native_arch):
    if wine_arch == "aarch64" and native_arch != "arm64-v8a":
        raise ValueError("aarch64 Wine requires arm64-v8a native libraries")
    names = {p.name for p in directory.glob("*.so")}
    if names != set(PLUGINS):
        raise ValueError(f"GStreamer inventory mismatch: missing={sorted(set(PLUGINS)-names)}, extra={sorted(names-set(PLUGINS))}")
    files = {}
    for name in PLUGINS:
        data = (directory / name).read_bytes()
        check_elf(data, wine_arch, name)
        files[name] = hashlib.sha256(data).hexdigest()
    box64 = wine_arch == "x86_64" and native_arch == "arm64-v8a"
    return {"version": VERSION, "storage": "payload" if box64 else "native-libs",
            "nativeArch": native_arch,
            "pluginDirectory": f"bin/{wine_arch}-unix/gstreamer-1.0" if box64 else f"libs/{native_arch}",
            "pluginCount": len(PLUGINS), "requiredPlugins": list(REQUIRED_PLUGINS),
            "requiredElements": list(REQUIRED_ELEMENTS), "files": files,
            "inventorySha256": fingerprint(files)}


def write_header(path, metadata):
    lines = ["/* Generated by gstreamer_inventory.py; do not edit. */",
             "#ifndef WINEHUA_GST_INVENTORY_H", "#define WINEHUA_GST_INVENTORY_H",
             '#define WINEHUA_GST_INVENTORY_SHA256 "' + metadata["inventorySha256"] + '"',
             'static const char winehua_gst_inventory_identity[] = "winehua-gst-inventory:" WINEHUA_GST_INVENTORY_SHA256;',
             "static const char * const winehua_gst_plugins[] = {"]
    lines += ['    "' + name + '",' for name in PLUGINS]
    lines += ["};", "static const char * const winehua_gst_required_elements[] = {"]
    lines += ['    "' + name + '",' for name in REQUIRED_ELEMENTS]
    lines += ["};", "#endif", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    content = "\n".join(lines)
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plugins-dir", type=Path, required=True)
    parser.add_argument("--wine-arch", choices=("aarch64", "x86_64"), required=True)
    parser.add_argument("--native-arch", choices=("arm64-v8a", "x86_64"), required=True)
    parser.add_argument("--package-to", type=Path)
    parser.add_argument("--header", type=Path)
    parser.add_argument("--metadata", type=Path)
    args = parser.parse_args()
    metadata = describe(args.plugins_dir, args.wine_arch, args.native_arch)
    if args.package_to:
        args.package_to.mkdir(parents=True, exist_ok=True)
        for name in PLUGINS:
            shutil.copyfile(args.plugins_dir / name, args.package_to / name)
    if args.header:
        write_header(args.header, metadata)
    if args.metadata:
        args.metadata.write_text(json.dumps(metadata, indent=2) + "\n")
    print(f"GStreamer {VERSION}: {len(PLUGINS)} plugins, {metadata['storage']}, inventory={metadata['inventorySha256']}")


if __name__ == "__main__":
    main()
